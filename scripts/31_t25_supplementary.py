"""31（任务 #25b）：补齐补充材料包。

1. 把 S1/S2/S3 的 CSV 从 manuscript/ 复制进 manuscript/supplementary/（原来只有 S4~S10 在里面）
2. 把 Supplementary Note S1/S2 的正文作为两个工作表并入合并工作簿，并在目录页登记
3. 用 pandoc 把两个附注转成 supplementary_notes_S1_S2.docx
4. 打印清单核对

前置：先跑 src/20_t21_supp_tables.py（它重建 CSV 和工作簿）。
用法: python src/31_t25_supplementary.py
"""
import os
import re
import shutil
import subprocess

import openpyxl
from openpyxl.styles import Alignment, Font

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
R = lambda *p: os.path.join(ROOT, *p)
OUT = R('manuscript', 'supplementary')
PANDOC = os.environ.get('PANDOC', 'pandoc')

# 1. S1~S3 的 CSV 进补充材料目录
for name in ['supp_table_S1.csv', 'supp_table_S2.csv', 'supp_table_S3.csv']:
    shutil.copy2(R('manuscript', name), os.path.join(OUT, name))
    print('copied', name)

# 2. 附注并入工作簿
notes = open(os.path.join(OUT, 'supplementary_notes_S1_S2.md'), encoding='utf-8').read()
parts = re.split(r'\n## ', notes)
sections = [('NoteS1', p) for p in parts if p.startswith('Supplementary Note S1')]
sections += [('NoteS2', p) for p in parts if p.startswith('Supplementary Note S2')]
assert len(sections) == 2, [p[:40] for p in parts]

xlsx = os.path.join(OUT, 'supplementary_tables_S1_S10.xlsx')
wb = openpyxl.load_workbook(xlsx)
toc = wb['Contents']
for sheet, body in sections:
    if sheet in wb.sheetnames:
        del wb[sheet]
    ws = wb.create_sheet(sheet)
    title = body.split('\n', 1)[0].strip()
    ws['A1'] = title
    ws['A1'].font = Font(bold=True, size=13)
    row = 3
    for para in body.split('\n', 1)[1].split('\n'):
        para = para.strip()
        if not para or para == '---':
            continue
        # 去掉 markdown 粗体/斜体标记，工作表里只放纯文本
        txt = re.sub(r'\*\*(.+?)\*\*', r'\1', para)
        txt = re.sub(r'\*(.+?)\*', r'\1', txt)
        txt = re.sub(r'`(.+?)`', r'\1', txt)
        ws.cell(row, 1, txt).alignment = Alignment(wrap_text=True, vertical='top')
        ws.row_dimensions[row].height = max(15, 15 * (len(txt) // 110 + 1))
        row += 2
    ws.column_dimensions['A'].width = 130
    toc.append([sheet, title.split('.')[0].replace('Supplementary ', ''), '',
                title.split('. ', 1)[1] + ' (text, also in supplementary_notes_S1_S2.md/.docx)'])
    print('sheet', sheet, 'rows', row)

# 目录页末尾那句「Generated by ...」原本在表格后面，移到最后
rows = [[c.value for c in r] for r in toc.iter_rows()]
gen = [i for i, r in enumerate(rows) if r[0] and str(r[0]).startswith('Generated by')]
if gen:
    i = gen[0]
    toc.delete_rows(i + 1)
    toc.append([f'Generated by src/20_t21_supp_tables.py and src/31_t25_supplementary.py; every number '
                f'traces to results/ in the project repository (see README.md in the release package).'])
for row in toc.iter_rows(min_row=4):
    if row[3].value:
        row[3].alignment = Alignment(wrap_text=True, vertical='top')
wb.save(xlsx)
print('workbook sheets:', wb.sheetnames)

# 3. 附注转 docx
docx_out = os.path.join(OUT, 'supplementary_notes_S1_S2.docx')
subprocess.run([PANDOC, os.path.join(OUT, 'supplementary_notes_S1_S2.md'), '-o', docx_out, '--standalone'],
               check=True)
print('notes docx ->', docx_out)

# 4. 清单
print('\n补充材料目录内容：')
for f in sorted(os.listdir(OUT)):
    print(f'  {f:52s} {os.path.getsize(os.path.join(OUT, f)):>9,d} B')
